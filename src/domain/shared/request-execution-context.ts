import type { StageTimer } from '../../observability/stage-timer.js';

/**
 * Request-scoped execution knobs forwarded from HTTP (or batch parent) into
 * application use cases. Extend deliberately — avoid diverging inline option bags.
 */
export interface RequestExecutionContext {
  /**
   * Explicit trust-domain for the execution path.
   * `benchmark_trusted` is reserved for internally authenticated benchmark lanes
   * and skips public-edge query-entry security so retrieval quality can be
   * measured independently from prompt-injection defenses.
   */
  readonly executionPrincipal?: 'public' | 'benchmark_trusted' | undefined;
  readonly abortSignal?: AbortSignal | undefined;
  /**
   * True when the HTTP request passed X-Debug-Key validation.
   * Planner/audit trace gates may use this to enable debug-only observability.
   */
  readonly debugRequest?: boolean | undefined;
  /**
   * Per-request stage latency tracker. Domain code may call
   * `stageTimer?.start(name)` / `stageTimer?.end(name)` around hot stages
   * (retrieval channels, fusion, ranking, second-phase) so the route
   * handler can read a flat snapshot at the end of the request and emit
   * it through the observability log line. Optional so unit tests and
   * background jobs can omit it without wrapping every call.
   */
  readonly stageTimer?: StageTimer | undefined;
  /**
   * Opaque request identifier propagated from the HTTP `X-Request-Id` header
   * (or generated by the route handler). Forwarded to downstream infrastructure
   * adapters (e.g. Vespa, LLM providers) so distributed traces can be correlated
   * across service boundaries without requiring a full tracing SDK.
   */
  readonly requestId?: string | undefined;
}
