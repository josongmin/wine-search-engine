// ---------------------------------------------------------------------------
// Deterministic embedding from sensory profile
// ---------------------------------------------------------------------------

/**
 * Generates a deterministic 128-dim unit-norm embedding from the four core
 * sensory attributes.  Semantically similar wines (similar body / sweetness /
 * acidity / tannin) will produce similar vectors, which is useful for ANN
 * smoke-tests without a real embedding model.
 */
function makeEmbedding(
  body: number,
  sweetness: number,
  acidity: number,
  tannin: number,
): readonly number[] {
  const features = [
    body, sweetness, acidity, tannin,
    1 - body, 1 - sweetness, 1 - acidity, 1 - tannin,
  ];
  const embedding = new Array<number>(1024).fill(0);
  for (let i = 0; i < 1024; i++) {
    const f = features[i % features.length]!;
    const k = Math.floor(i / features.length);
    embedding[i] = f * Math.cos(k * Math.PI / 8) + (1 - f) * Math.sin(k * Math.PI / 8);
  }
  const norm = Math.sqrt(embedding.reduce((s, x) => s + x * x, 0));
  return embedding.map((x) => x / norm);
}

// ---------------------------------------------------------------------------
// Price-band helper
// ---------------------------------------------------------------------------

function priceBand(priceUsd: number): string {
  if (priceUsd >= 500) return 'luxury';
  if (priceUsd >= 100) return 'premium';
  if (priceUsd >= 30)  return 'mid';
  return 'value';
}

export function applyDefaultDrinkingWindowModelVersion(
  docs: readonly RetrievalDocument[],
): readonly RetrievalDocument[] {
  return docs.map((doc) => {
    if (
      doc.drinkingWindowStart === undefined
      || doc.drinkingWindowEnd === undefined
      || doc.drinkingWindowModelVersion !== undefined
    ) {
      return doc;
    }

    return {
      ...doc,
      drinkingWindowModelVersion: DEFAULT_LEARNED_DRINKING_WINDOW_MODEL_VERSION,
    };
  });
}

